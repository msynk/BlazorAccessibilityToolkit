using System.Globalization;
using System.Text;

namespace BlazorAccessibilityToolkit.Reporting;

/// <summary>Product and contact details for conformance report drafts. Missing values are written as <c>TODO</c> placeholders.</summary>
public sealed record ConformanceReportInfo
{
    /// <summary>Product name.</summary>
    public string? ProductName { get; init; }

    /// <summary>Product version.</summary>
    public string? ProductVersion { get; init; }

    /// <summary>Short product description.</summary>
    public string? ProductDescription { get; init; }

    /// <summary>Organization that makes the product.</summary>
    public string? Organization { get; init; }

    /// <summary>Report author or accessibility contact.</summary>
    public string? ContactName { get; init; }

    /// <summary>Contact email (OpenACR requires one; the EAA statement needs a feedback channel).</summary>
    public string? ContactEmail { get; init; }

    /// <summary>Highest WCAG level to include. Default AA.</summary>
    public WcagLevel Level { get; init; } = WcagLevel.AA;

    /// <summary>Report date. Default: the report's generation date.</summary>
    public DateOnly? Date { get; init; }
}

/// <summary>
/// A draft accessibility conformance report in the OpenACR format (GSA, <see href="https://github.com/GSA/openacr"/>),
/// catalog <c>2.5-edition-wcag-2.2-en</c> (VPAT 2.5 WCAG edition), for web content.
/// </summary>
/// <remarks>
/// It is a draft for an accessibility specialist to complete, never a finished report. Following
/// <see cref="WcagCoverage"/>, a criterion is "supports" only when a recorded manual review passed it, "does-not-support"
/// when a violation or failed manual check maps to it, and "not-evaluated" otherwise, with a note saying what evidence
/// exists. Criteria marked not-evaluated at levels A and AA must be evaluated before the report is published.
/// </remarks>
public sealed class OpenAcrReportFormatter : IReportFormatter
{
    /// <summary>OpenACR catalog used for the chapters and criteria.</summary>
    public const string Catalog = "2.5-edition-wcag-2.2-en";

    /// <summary>Product and contact details.</summary>
    public ConformanceReportInfo Info { get; init; } = new();

    /// <inheritdoc />
    public string Name => "openacr";

    /// <inheritdoc />
    public string DefaultFileName => "accessibility-conformance-report.openacr.yaml";

    /// <summary>The OpenACR adherence level for a coverage conclusion.</summary>
    public static string AdherenceLevel(CriterionConformance conformance) => conformance switch
    {
        CriterionConformance.Supports => "supports",
        CriterionConformance.DoesNotSupport => "does-not-support",
        CriterionConformance.NotApplicable => "not-applicable",
        _ => "not-evaluated",
    };

    /// <inheritdoc />
    public void Write(AccessibilityReport report, TextWriter writer)
    {
        ArgumentNullException.ThrowIfNull(report);
        ArgumentNullException.ThrowIfNull(writer);
        var info = Info;
        var date = (info.Date ?? DateOnly.FromDateTime(report.GeneratedAt.UtcDateTime)).ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);
        var rows = WcagCoverage.Create(report, info.Level);

        writer.Write("# Draft accessibility conformance report generated by ");
        writer.Write(report.Tool.Name);
        writer.Write(' ');
        writer.WriteLine(report.Tool.Version);
        writer.WriteLine("# Complete every TODO and evaluate every not-evaluated criterion before publishing. Automated checks cannot establish conformance.");
        Line(writer, 0, "title", $"{info.ProductName ?? "TODO product"} Accessibility Conformance Report");
        writer.WriteLine("product:");
        Line(writer, 1, "name", info.ProductName ?? "TODO product name");
        Line(writer, 1, "version", info.ProductVersion ?? "TODO");
        if (info.ProductDescription is not null)
        {
            Line(writer, 1, "description", info.ProductDescription);
        }

        writer.WriteLine("author:");
        Line(writer, 1, "name", info.ContactName ?? "TODO");
        Line(writer, 1, "company_name", info.Organization ?? "TODO");
        Line(writer, 1, "email", info.ContactEmail ?? "TODO@example.com");
        writer.WriteLine("vendor:");
        Line(writer, 1, "company_name", info.Organization ?? "TODO");
        Line(writer, 1, "email", info.ContactEmail ?? "TODO@example.com");
        Line(writer, 0, "report_date", date);
        Line(writer, 0, "last_modified_date", date);
        writer.WriteLine("version: 1");
        Line(writer, 0, "notes", "DRAFT. Generated from automated test results and recorded manual reviews. \"supports\" is only used where a person verified the criterion.");
        Line(writer, 0, "evaluation_methods_used", EvaluationMethods(report));
        Line(writer, 0, "license", "CC-BY-4.0");
        Line(writer, 0, "catalog", Catalog);
        writer.WriteLine("chapters:");
        foreach (var (chapter, level) in new[] { ("success_criteria_level_a", WcagLevel.A), ("success_criteria_level_aa", WcagLevel.AA), ("success_criteria_level_aaa", WcagLevel.AAA) })
        {
            if (level > info.Level)
            {
                continue;
            }

            writer.Write("  ");
            writer.Write(chapter);
            writer.WriteLine(':');
            Line(writer, 2, "notes", string.Empty);
            writer.WriteLine("    criteria:");
            foreach (var row in rows.Where(r => r.Criterion.Level == level))
            {
                writer.Write("      - num: ");
                writer.WriteLine(Quote(row.Criterion.Id));
                writer.WriteLine("        components:");
                writer.WriteLine("          - name: web");
                writer.WriteLine("            adherence:");
                Line(writer, 7, "level", AdherenceLevel(row.Conformance));
                Line(writer, 7, "notes", Notes(row));
            }
        }
    }

    internal static string Notes(WcagCriterionCoverage row)
    {
        var parts = new List<string>();
        if (row.Violations > 0)
        {
            parts.Add(string.Create(CultureInfo.InvariantCulture, $"{row.Violations} automated violation(s)"));
        }

        if (row.PotentialIssues > 0)
        {
            parts.Add(string.Create(CultureInfo.InvariantCulture, $"{row.PotentialIssues} potential issue(s) to review"));
        }

        if (row.Inconclusive > 0)
        {
            parts.Add(string.Create(CultureInfo.InvariantCulture, $"{row.Inconclusive} inconclusive result(s)"));
        }

        if (row.Rules.Count > 0)
        {
            parts.Add("rules: " + string.Join(", ", row.Rules));
        }

        if (row.ManualChecks.Count > 0)
        {
            parts.Add("manual checks: " + string.Join(", ", row.ManualChecks));
        }

        var evidence = parts.Count == 0 ? "No automated finding and no manual review." : string.Join("; ", parts) + ".";
        return row.Conformance switch
        {
            CriterionConformance.NotEvaluated => "DRAFT: not evaluated. " + evidence,
            CriterionConformance.NeedsReview => "DRAFT: needs review. " + evidence,
            _ => evidence,
        };
    }

    internal static string EvaluationMethods(AccessibilityReport report)
    {
        var engines = report.Audits.SelectMany(a => a.Engines).Select(e => e.Version is null ? e.Name : $"{e.Name} {e.Version}").Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToArray();
        var browsers = report.Audits.Select(a => a.Context.Browser is null ? null : $"{a.Context.Browser} {a.Context.BrowserVersion}".Trim()).Where(b => b is not null).Distinct(StringComparer.Ordinal).ToArray();
        var sb = new StringBuilder("Automated testing");
        if (engines.Length > 0)
        {
            sb.Append(" with ").Append(string.Join(", ", engines));
        }

        if (browsers.Length > 0)
        {
            sb.Append(" in ").Append(string.Join(", ", browsers));
        }

        sb.Append(string.Create(CultureInfo.InvariantCulture, $" ({report.Summary.Audits} audits)"));
        if (report.ManualReviews.Count > 0)
        {
            sb.Append("; manual review checklists: ").Append(string.Join(", ", report.ManualReviews.Select(m => m.Name)));
        }

        return sb.Append('.').ToString();
    }

    private static void Line(TextWriter writer, int depth, string key, string value)
    {
        writer.Write(new string(' ', depth * 2));
        writer.Write(key);
        writer.Write(": ");
        writer.WriteLine(Quote(value));
    }

    // A double-quoted YAML scalar.
    internal static string Quote(string value)
    {
        var sb = new StringBuilder("\"");
        foreach (var c in value)
        {
            switch (c)
            {
                case '"': sb.Append("\\\""); break;
                case '\\': sb.Append("\\\\"); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': break;
                case '\t': sb.Append("\\t"); break;
                default:
                    if (char.IsControl(c))
                    {
                        sb.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        sb.Append(c);
                    }

                    break;
            }
        }

        return sb.Append('"').ToString();
    }
}

/// <summary>
/// A draft accessibility statement in Markdown, structured like the model statement of the EU Web Accessibility
/// Directive and the information that the European Accessibility Act (Annex V) asks service providers to publish:
/// compliance status, non-accessible content, how the statement was prepared, feedback and enforcement.
/// </summary>
/// <remarks>
/// The compliance status is never "fully compliant": automated checks and partial manual reviews cannot establish it.
/// The draft lists the evidence and leaves the legal and contact sections as <c>TODO</c> placeholders.
/// </remarks>
public sealed class AccessibilityStatementFormatter : IReportFormatter
{
    /// <summary>Product and contact details.</summary>
    public ConformanceReportInfo Info { get; init; } = new();

    /// <inheritdoc />
    public string Name => "statement";

    /// <inheritdoc />
    public string DefaultFileName => "accessibility-statement.md";

    /// <inheritdoc />
    public void Write(AccessibilityReport report, TextWriter writer)
    {
        ArgumentNullException.ThrowIfNull(report);
        ArgumentNullException.ThrowIfNull(writer);
        var info = Info;
        var rows = WcagCoverage.Create(report, info.Level);
        var product = info.ProductName ?? "TODO product name";
        var organization = info.Organization ?? "TODO organization";
        var date = (info.Date ?? DateOnly.FromDateTime(report.GeneratedAt.UtcDateTime)).ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);
        var failing = rows.Where(r => r.Conformance == CriterionConformance.DoesNotSupport).ToArray();
        var open = rows.Where(r => r.Conformance is CriterionConformance.NeedsReview or CriterionConformance.NotEvaluated).ToArray();
        var level = info.Level.ToString();

        writer.WriteLine($"# Accessibility statement for {product}");
        writer.WriteLine();
        writer.WriteLine($"> DRAFT generated by {report.Tool.Name} {report.Tool.Version} on {date}. Review every section, replace each TODO, and have the compliance status confirmed by an accessibility specialist before publishing. Automated checks find only some accessibility problems.");
        writer.WriteLine();
        writer.WriteLine($"{organization} is committed to making {product} accessible. This statement applies to {product}{(info.ProductVersion is null ? string.Empty : " version " + info.ProductVersion)}.");
        writer.WriteLine();
        writer.WriteLine("## Compliance status");
        writer.WriteLine();
        writer.WriteLine($"The target is WCAG 2.2 level {level}, which is also the web content requirement of EN 301 549 (clause 9).");
        writer.WriteLine();
        writer.WriteLine(failing.Length > 0
            ? $"{product} is **partially compliant**: the non-accessible content listed below does not yet meet {failing.Length} success criteria."
            : $"TODO: state whether {product} is fully or partially compliant. No automated violation was found, but {open.Length} success criteria have not been fully evaluated by a person.");
        writer.WriteLine();
        writer.WriteLine("## Non-accessible content");
        writer.WriteLine();
        if (failing.Length == 0)
        {
            writer.WriteLine("No failures are recorded. TODO: list known issues, disproportionate burden claims and content outside the scope of the law, if any.");
        }
        else
        {
            writer.WriteLine("The following content does not meet the requirements:");
            writer.WriteLine();
            foreach (var row in failing)
            {
                var clause = row.En301549Clause is null ? string.Empty : $", EN 301 549 {row.En301549Clause}";
                writer.WriteLine($"- **{row.Criterion.Id} {row.Criterion.Title}** (level {row.Criterion.Level}{clause}): {OpenAcrReportFormatter.Notes(row)} TODO: describe the effect on users and when it will be fixed.");
            }
        }

        writer.WriteLine();
        writer.WriteLine("## Preparation of this statement");
        writer.WriteLine();
        writer.WriteLine($"This statement was prepared on {date}. Evaluation: {OpenAcrReportFormatter.EvaluationMethods(report)}");
        if (open.Length > 0)
        {
            writer.WriteLine();
            writer.WriteLine($"Not yet evaluated or awaiting review ({open.Length}): {string.Join(", ", open.Select(r => r.Criterion.Id))}.");
        }

        writer.WriteLine();
        writer.WriteLine("## Feedback and contact information");
        writer.WriteLine();
        writer.WriteLine($"If you find an accessibility barrier, or need information in an accessible format, contact {info.ContactName ?? "TODO name"} at {info.ContactEmail ?? "TODO email"}. TODO: say when you will respond.");
        writer.WriteLine();
        writer.WriteLine("## Enforcement procedure");
        writer.WriteLine();
        writer.WriteLine("TODO: name the national authority responsible for enforcement (for the European Accessibility Act, the market surveillance authority of the member state) and how to contact it if a response is unsatisfactory.");
    }
}
