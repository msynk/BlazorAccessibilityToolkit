using System.Text;

namespace BlazorAccessibilityToolkit.Analyzers.Tests;

/// <summary>
/// The primary language subtags that BA11Y028 accepts, generated from the IANA Language Subtag Registry into
/// src/BlazorAccessibilityToolkit.Analyzers/LanguageSubtags.cs.
/// </summary>
public sealed class LanguageSubtagsTests
{
    private const string Registry = "https://www.iana.org/assignments/language-subtag-registry/language-subtag-registry";

    [Theory]
    [InlineData("en", true)]
    [InlineData("fr", true)]
    [InlineData("iw", true)] // deprecated, still registered
    [InlineData("haw", true)]
    [InlineData("qab", true)] // private use range qaa..qtz
    [InlineData("eng", false)] // "en" is the subtag for English
    [InlineData("em", false)]
    [InlineData("xyz", false)]
    [InlineData("english", false)]
    [InlineData("EN", true)]
    public void Knows_the_registered_primary_language_subtags(string subtag, bool registered) =>
        Assert.Equal(registered, LanguageSubtags.IsPrimaryLanguage(subtag));

    /// <summary>Regenerates LanguageSubtags.cs. Runs only with BLAZOR_A11Y_UPDATE_LANGUAGE_SUBTAGS=1.</summary>
    [Fact]
    public async Task Update_the_language_subtags()
    {
        if (Environment.GetEnvironmentVariable("BLAZOR_A11Y_UPDATE_LANGUAGE_SUBTAGS") is not ("1" or "true"))
        {
            Assert.Skip("Set BLAZOR_A11Y_UPDATE_LANGUAGE_SUBTAGS=1 to download the IANA Language Subtag Registry.");
        }

        using var http = new HttpClient { Timeout = TimeSpan.FromMinutes(2) };
        var text = (await http.GetStringAsync(new Uri(Registry), TestContext.Current.CancellationToken)).ReplaceLineEndings("\n");
        var records = text.Split("\n%%\n");
        var fileDate = records[0].Split('\n').First(l => l.StartsWith("File-Date: ", StringComparison.Ordinal))["File-Date: ".Length..].Trim();
        var subtags = new List<string>();
        foreach (var record in records.Skip(1))
        {
            var fields = record.Split('\n').Where(l => l.Contains(": ", StringComparison.Ordinal) && !l.StartsWith(' ')).Select(l => l.Split(": ", 2)).GroupBy(p => p[0]).ToDictionary(g => g.Key, g => g.First()[1].Trim());
            if (fields.GetValueOrDefault("Type") == "language" && fields["Subtag"] is { Length: 2 or 3 } subtag && subtag.All(char.IsAsciiLetterLower))
            {
                subtags.Add(subtag);
            }
        }

        var sb = new StringBuilder();
        sb.Append("// <auto-generated>\n");
        sb.Append(System.Globalization.CultureInfo.InvariantCulture, $"// Generated from the IANA Language Subtag Registry ({Registry}), File-Date {fileDate},\n");
        sb.Append("// by LanguageSubtagsTests.Update_the_language_subtags (BLAZOR_A11Y_UPDATE_LANGUAGE_SUBTAGS=1). Do not edit.\n");
        sb.Append("// </auto-generated>\n\n");
        sb.Append("namespace BlazorAccessibilityToolkit.Analyzers;\n\n");
        sb.Append("/// <summary>The registered primary language subtags (two and three letters), for checking lang attributes.</summary>\n");
        sb.Append("internal static class LanguageSubtags\n{\n");
        sb.Append(System.Globalization.CultureInfo.InvariantCulture, $"    public const string FileDate = \"{fileDate}\";\n\n");
        foreach (var (name, length) in new[] { ("Two", 2), ("Three", 3) })
        {
            var codes = subtags.Where(s => s.Length == length).Order(StringComparer.Ordinal).ToArray();
            sb.Append(System.Globalization.CultureInfo.InvariantCulture, $"    private const string {name} =\n");
            var lines = codes.Chunk(40).Select(chunk => "        \"" + string.Concat(chunk) + "\"").ToArray();
            sb.Append(string.Join(" +\n", lines)).Append(";\n\n");
        }

        sb.Append("""
                private static readonly HashSet<string> Codes = new(Split(Two, 2).Concat(Split(Three, 3)), StringComparer.Ordinal);

                /// <summary>Whether the subtag is a registered primary language subtag, or in the private use range qaa..qtz.</summary>
                public static bool IsPrimaryLanguage(string subtag)
                {
                    var lower = subtag.ToLowerInvariant();
                    return Codes.Contains(lower) || (lower.Length == 3 && lower[0] == 'q' && lower[1] >= 'a' && lower[1] <= 't' && lower[2] >= 'a' && lower[2] <= 'z');
                }

                private static IEnumerable<string> Split(string codes, int length)
                {
                    for (var i = 0; i < codes.Length; i += length)
                    {
                        yield return codes.Substring(i, length);
                    }
                }
            }

            """);
        var path = Path.Combine(Root(), "src", "BlazorAccessibilityToolkit.Analyzers", "LanguageSubtags.cs");
        await File.WriteAllTextAsync(path, sb.ToString(), TestContext.Current.CancellationToken);
    }

    private static string Root([System.Runtime.CompilerServices.CallerFilePath] string source = "") =>
        Path.GetFullPath(Path.Combine(Path.GetDirectoryName(source)!, "..", ".."));
}
